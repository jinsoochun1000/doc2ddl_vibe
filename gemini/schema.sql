-- [1] 마스터: 개인이력카드 기본정보
CREATE TABLE TB_RESUME (
    RESUME_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    FULL_NAME           VARCHAR2(50 CHAR)       NOT NULL,
    BIRTH_DATE          DATE,
    GENDER              VARCHAR2(10 CHAR),
    COMPANY_NAME        VARCHAR2(100 CHAR),
    HIRE_DATE           DATE,
    DEPARTMENT          VARCHAR2(100 CHAR),
    POSITION            VARCHAR2(50 CHAR),
    MILITARY_STATUS     VARCHAR2(50 CHAR),
    PHONE               VARCHAR2(30 CHAR),
    EMAIL               VARCHAR2(100 CHAR),
    ADDRESS             VARCHAR2(300 CHAR),
    OTHER_SKILLS_NOTE   VARCHAR2(1000 CHAR),
    CREATED_AT          DATE DEFAULT SYSDATE    NOT NULL,
    UPDATED_AT          DATE DEFAULT SYSDATE    NOT NULL,
    CONSTRAINT PK_TB_RESUME PRIMARY KEY (RESUME_ID)
);

-- [2] 학력사항
CREATE TABLE TB_RESUME_EDUCATION (
    EDUCATION_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    RESUME_ID           NUMBER                  NOT NULL,
    SCHOOL_NAME         VARCHAR2(100 CHAR)      NOT NULL,
    MAJOR               VARCHAR2(100 CHAR),
    ADMISSION_DATE      DATE,
    GRADUATION_DATE     DATE,
    GRADUATION_STATUS   VARCHAR2(20 CHAR),
    SORT_ORDER          NUMBER(3) DEFAULT 1     NOT NULL,
    CONSTRAINT PK_TB_RESUME_EDUCATION PRIMARY KEY (EDUCATION_ID),
    CONSTRAINT FK_TB_RESUME_EDU_RESUME FOREIGN KEY (RESUME_ID)
        REFERENCES TB_RESUME (RESUME_ID) ON DELETE CASCADE,
    CONSTRAINT CK_TB_RESUME_EDU_DATE CHECK (
        GRADUATION_DATE IS NULL OR ADMISSION_DATE IS NULL OR GRADUATION_DATE >= ADMISSION_DATE
    )
);

-- [3] 자격사항
CREATE TABLE TB_RESUME_CERTIFICATE (
    CERTIFICATE_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    RESUME_ID           NUMBER                  NOT NULL,
    CERTIFICATE_NAME    VARCHAR2(150 CHAR)      NOT NULL,
    ACQUIRED_DATE       DATE,
    ISSUER              VARCHAR2(100 CHAR),
    SORT_ORDER          NUMBER(3) DEFAULT 1     NOT NULL,
    CONSTRAINT PK_TB_RESUME_CERTIFICATE PRIMARY KEY (CERTIFICATE_ID),
    CONSTRAINT FK_TB_RESUME_CERT_RESUME FOREIGN KEY (RESUME_ID)
        REFERENCES TB_RESUME (RESUME_ID) ON DELETE CASCADE
);

-- [4] 경력사항
CREATE TABLE TB_RESUME_CAREER (
    CAREER_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    RESUME_ID           NUMBER                  NOT NULL,
    COMPANY_NAME        VARCHAR2(100 CHAR)      NOT NULL,
    START_DATE          DATE                    NOT NULL,
    END_DATE            DATE,
    IS_CURRENT          CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    POSITION            VARCHAR2(50 CHAR),
    JOB_DESCRIPTION     VARCHAR2(1000 CHAR),
    SORT_ORDER          NUMBER(3) DEFAULT 1     NOT NULL,
    CONSTRAINT PK_TB_RESUME_CAREER PRIMARY KEY (CAREER_ID),
    CONSTRAINT FK_TB_RESUME_CAR_RESUME FOREIGN KEY (RESUME_ID)
        REFERENCES TB_RESUME (RESUME_ID) ON DELETE CASCADE,
    CONSTRAINT CK_TB_RESUME_CAR_CURRENT CHECK (IS_CURRENT IN ('Y', 'N')),
    CONSTRAINT CK_TB_RESUME_CAR_DATE CHECK (
        END_DATE IS NULL OR END_DATE >= START_DATE
    )
);

-- [5] 교육 및 연수사항
CREATE TABLE TB_RESUME_TRAINING (
    TRAINING_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    RESUME_ID           NUMBER                  NOT NULL,
    TRAINING_NAME       VARCHAR2(150 CHAR)      NOT NULL,
    START_DATE          DATE,
    END_DATE            DATE,
    INSTITUTION         VARCHAR2(100 CHAR),
    SORT_ORDER          NUMBER(3) DEFAULT 1     NOT NULL,
    CONSTRAINT PK_TB_RESUME_TRAINING PRIMARY KEY (TRAINING_ID),
    CONSTRAINT FK_TB_RESUME_TRAIN_RESUME FOREIGN KEY (RESUME_ID)
        REFERENCES TB_RESUME (RESUME_ID) ON DELETE CASCADE,
    CONSTRAINT CK_TB_RESUME_TRAIN_DATE CHECK (
        END_DATE IS NULL OR START_DATE IS NULL OR END_DATE >= START_DATE
    )
);

-- [6] 보유기술 및 외국어능력
CREATE TABLE TB_RESUME_SKILL (
    SKILL_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    RESUME_ID           NUMBER                  NOT NULL,
    SKILL_NAME          VARCHAR2(100 CHAR)      NOT NULL,
    SKILL_LEVEL         VARCHAR2(20 CHAR),
    SKILL_TYPE          VARCHAR2(50 CHAR),
    SORT_ORDER          NUMBER(3) DEFAULT 1     NOT NULL,
    CONSTRAINT PK_TB_RESUME_SKILL PRIMARY KEY (SKILL_ID),
    CONSTRAINT FK_TB_RESUME_SKL_RESUME FOREIGN KEY (RESUME_ID)
        REFERENCES TB_RESUME (RESUME_ID) ON DELETE CASCADE
);

-- [7] SKILL INVENTORY: 프로젝트 수행이력
CREATE TABLE TB_RESUME_PROJECT (
    PROJECT_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    RESUME_ID           NUMBER                  NOT NULL,
    PROJECT_NAME        VARCHAR2(200 CHAR)      NOT NULL,
    START_DATE          DATE                    NOT NULL,
    END_DATE            DATE,
    CLIENT_COMPANY      VARCHAR2(100 CHAR),
    WORKING_COMPANY     VARCHAR2(100 CHAR),
    ROLE                VARCHAR2(100 CHAR),
    DEV_HARDWARE        VARCHAR2(100 CHAR),
    DEV_OS              VARCHAR2(100 CHAR),
    DEV_LANGUAGE        VARCHAR2(100 CHAR),
    DEV_DBMS            VARCHAR2(100 CHAR),
    DEV_TOOL            VARCHAR2(200 CHAR),
    DEV_COMMUNICATION   VARCHAR2(100 CHAR),
    DEV_WAS             VARCHAR2(100 CHAR),
    TASK_DESCRIPTION    VARCHAR2(2000 CHAR),
    SORT_ORDER          NUMBER(3) DEFAULT 1     NOT NULL,
    CONSTRAINT PK_TB_RESUME_PROJECT PRIMARY KEY (PROJECT_ID),
    CONSTRAINT FK_TB_RESUME_PRJ_RESUME FOREIGN KEY (RESUME_ID)
        REFERENCES TB_RESUME (RESUME_ID) ON DELETE CASCADE,
    CONSTRAINT CK_TB_RESUME_PRJ_DATE CHECK (
        END_DATE IS NULL OR END_DATE >= START_DATE
    )
);

