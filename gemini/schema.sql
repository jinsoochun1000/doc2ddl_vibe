-- 1. 기존 테이블 및 객체 삭제 (안전한 재실행을 위한 PL/SQL 블록)
-- --------------------------------------------------------------------
BEGIN
    FOR t IN (
        SELECT table_name 
        FROM user_tables 
        WHERE table_name IN (
            'TB_RESUME_PROJECT',
            'TB_RESUME_SKILL',
            'TB_RESUME_TRAINING',
            'TB_RESUME_CAREER',
            'TB_RESUME_CERTIFICATE',
            'TB_RESUME_EDUCATION',
            'TB_RESUME'
        )
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
