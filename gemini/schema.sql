-- 6. 데이터 검증 뷰 (통합 이력 프로필 조회 뷰)
-- --------------------------------------------------------------------
CREATE OR REPLACE VIEW VW_RESUME_OVERVIEW AS
SELECT 
    r.RESUME_ID,
    r.FULL_NAME,
    r.ADDRESS,
    (SELECT COUNT(*) FROM TB_RESUME_CAREER c WHERE c.RESUME_ID = r.RESUME_ID) AS CAREER_COUNT,
    (SELECT COUNT(*) FROM TB_RESUME_PROJECT p WHERE p.RESUME_ID = r.RESUME_ID) AS PROJECT_COUNT,
    (SELECT COUNT(*) FROM TB_RESUME_SKILL s WHERE s.RESUME_ID = r.RESUME_ID) AS SKILL_COUNT,
    r.OTHER_SKILLS_NOTE
FROM TB_RESUME r;
