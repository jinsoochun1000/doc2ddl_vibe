/* drop (children first)                                             */
/* ------------------------------------------------------------------ */

DECLARE
    TYPE name_list IS TABLE OF VARCHAR2(128);
    v_tables name_list := name_list(
        'RESUME_PROJECT',
        'RESUME_SKILL',
        'RESUME_TRAINING',
        'RESUME_CAREER',
        'RESUME_CERTIFICATE',
        'RESUME_EDUCATION',
        'RESUME'
    );
BEGIN
    FOR i IN 1 .. v_tables.COUNT LOOP
        BEGIN
            EXECUTE IMMEDIATE
                'DROP TABLE ' || v_tables(i) || ' CASCADE CONSTRAINTS PURGE';
        EXCEPTION
            WHEN OTHERS THEN
                IF SQLCODE != -942 THEN
                    RAISE;
                END IF;
        END;
    END LOOP;
END;
/

