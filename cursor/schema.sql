/* resume — 개인이력카드                                              */
/* ------------------------------------------------------------------ */

CREATE TABLE resume (
    resume_id         NUMBER         GENERATED BY DEFAULT AS IDENTITY,
    full_name         VARCHAR2(50 CHAR)   NOT NULL,          -- 성명
    birth_date        DATE,                                  -- 생년월일
    gender            VARCHAR2(10 CHAR),                     -- 성별
    company_name      VARCHAR2(100 CHAR),                    -- 소속회사
    hire_date         DATE,                                  -- 입사일자
    department        VARCHAR2(100 CHAR),                    -- 부서
    position          VARCHAR2(50 CHAR),                     -- 직위
    military_status   VARCHAR2(50 CHAR),                     -- 병적
    phone             VARCHAR2(30 CHAR),                     -- 전화
    email             VARCHAR2(200 CHAR),                    -- E-Mail
    address           VARCHAR2(300 CHAR),                    -- 주소
    other_skill_note  VARCHAR2(500 CHAR),                    -- 기타 (활용가능한 S/W 및 기법, FrameWork)
    CONSTRAINT pk_resume PRIMARY KEY (resume_id)
);

COMMENT ON TABLE resume IS '개인이력카드 기본 정보';
COMMENT ON COLUMN resume.full_name IS '성명';
COMMENT ON COLUMN resume.birth_date IS '생년월일';
COMMENT ON COLUMN resume.gender IS '성별';
COMMENT ON COLUMN resume.company_name IS '소속회사';
COMMENT ON COLUMN resume.hire_date IS '입사일자';
COMMENT ON COLUMN resume.department IS '부서';
COMMENT ON COLUMN resume.position IS '직위';
COMMENT ON COLUMN resume.military_status IS '병적';
COMMENT ON COLUMN resume.phone IS '전화';
COMMENT ON COLUMN resume.email IS 'E-Mail';
COMMENT ON COLUMN resume.address IS '주소';
COMMENT ON COLUMN resume.other_skill_note IS '기타 (활용가능한 S/W 및 기법, FrameWork)';

/* ------------------------------------------------------------------ */
/* resume_education — 학력사항                                        */
/* 양식 안내: 대학(교,원)의 입학일자도 표기                          */
/* ------------------------------------------------------------------ */

CREATE TABLE resume_education (
    education_id       NUMBER              GENERATED BY DEFAULT AS IDENTITY,
    resume_id          NUMBER              NOT NULL,
    school_name        VARCHAR2(100 CHAR)  NOT NULL,         -- 학교명
    major              VARCHAR2(100 CHAR),                   -- 전공/계열
    start_date         DATE,                                 -- 입학일
    end_date           DATE,                                 -- 졸업일
    graduation_status  VARCHAR2(20 CHAR),                    -- 졸업구분
    sort_order         NUMBER(5)           NOT NULL,         -- 문서 기재 순서
    CONSTRAINT pk_resume_education PRIMARY KEY (education_id),
    CONSTRAINT fk_resume_education_resume
        FOREIGN KEY (resume_id) REFERENCES resume (resume_id) ON DELETE CASCADE,
    CONSTRAINT ck_resume_education_dates
        CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date),
    CONSTRAINT ck_resume_education_sort
        CHECK (sort_order > 0)
);

CREATE INDEX ix_resume_education_resume_id
    ON resume_education (resume_id);

COMMENT ON TABLE resume_education IS '학력사항';
COMMENT ON COLUMN resume_education.school_name IS '학교명';
COMMENT ON COLUMN resume_education.major IS '전공/계열';
COMMENT ON COLUMN resume_education.start_date IS '입학일';
COMMENT ON COLUMN resume_education.end_date IS '졸업일';
COMMENT ON COLUMN resume_education.graduation_status IS '졸업구분';
COMMENT ON COLUMN resume_education.sort_order IS '문서 기재 순서';

