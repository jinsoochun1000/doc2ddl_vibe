/* resume_career — 경력                                               */
/* ------------------------------------------------------------------ */

CREATE TABLE resume_career (
    career_id     NUMBER              GENERATED BY DEFAULT AS IDENTITY,
    resume_id     NUMBER              NOT NULL,
    company_name  VARCHAR2(100 CHAR)  NOT NULL,              -- 회사명
    start_date    DATE,                                      -- 시작일
    end_date      DATE,                                      -- 종료일 (재직중이면 NULL)
    is_current    NUMBER(1)           DEFAULT 0 NOT NULL,    -- 재직중 (1/0)
    position      VARCHAR2(50 CHAR),                         -- 직위
    duties        VARCHAR2(500 CHAR),                        -- 담당업무
    sort_order    NUMBER(5)           NOT NULL,              -- 문서 기재 순서
    CONSTRAINT pk_resume_career PRIMARY KEY (career_id),
    CONSTRAINT fk_resume_career_resume
        FOREIGN KEY (resume_id) REFERENCES resume (resume_id) ON DELETE CASCADE,
    CONSTRAINT ck_resume_career_dates
        CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date),
    CONSTRAINT ck_resume_career_current
        CHECK (is_current IN (0, 1)),
    CONSTRAINT ck_resume_career_open_end
        CHECK (is_current = 0 OR end_date IS NULL),
    CONSTRAINT ck_resume_career_sort
        CHECK (sort_order > 0)
);

CREATE INDEX ix_resume_career_resume_id
    ON resume_career (resume_id);

COMMENT ON TABLE resume_career IS '경력';
COMMENT ON COLUMN resume_career.company_name IS '회사명';
COMMENT ON COLUMN resume_career.start_date IS '기간 시작일';
COMMENT ON COLUMN resume_career.end_date IS '기간 종료일. 재직중이면 NULL';
COMMENT ON COLUMN resume_career.is_current IS '재직중 여부 (1=재직중, 0=종료)';
COMMENT ON COLUMN resume_career.position IS '직위';
COMMENT ON COLUMN resume_career.duties IS '담당업무';
COMMENT ON COLUMN resume_career.sort_order IS '문서 기재 순서';

