CREATE TABLE resume_skill (
    skill_id     NUMBER              GENERATED BY DEFAULT AS IDENTITY,
    resume_id    NUMBER              NOT NULL,
    skill_name   VARCHAR2(100 CHAR)  NOT NULL,               -- 보유기술 및 외국어
    proficiency  VARCHAR2(1 CHAR),                           -- 숙련도 (A, B, C)
    sort_order   NUMBER(5)           NOT NULL,               -- 문서 기재 순서
    CONSTRAINT pk_resume_skill PRIMARY KEY (skill_id),
    CONSTRAINT fk_resume_skill_resume
        FOREIGN KEY (resume_id) REFERENCES resume (resume_id) ON DELETE CASCADE,
    CONSTRAINT ck_resume_skill_proficiency
        CHECK (proficiency IS NULL OR proficiency IN ('A', 'B', 'C')),
    CONSTRAINT ck_resume_skill_sort
        CHECK (sort_order > 0)
);

CREATE INDEX ix_resume_skill_resume_id
    ON resume_skill (resume_id);

