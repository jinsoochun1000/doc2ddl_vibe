/*
    개인이력카드 (../이력서.docx) — Oracle DDL + seed

    대상: Oracle 12c 이상 (IDENTITY 컬럼)
    권장 문자셋: AL32UTF8. 길이는 VARCHAR2(n CHAR)로 문자 수 기준.
    재실행 가능: 자식 테이블을 먼저 DROP 한 뒤 부모를 DROP 한다.
    빈 칸, '-', 'YYYY-MM-DD' 자리표시는 NULL.
    '재직중'은 END_DATE NULL, IS_CURRENT = 1.
*/

SET DEFINE OFF;

